// ---------- DERIVED HELPERS ----------
function getProgress(p) {
  return p.totalUnits > 0 ? (p.translatedUnits / p.totalUnits) * 100 : 0;
}
function getProjectStatus(p) {
  // Prefer explicit status field from CSV import
  if (p.status === 'em-andamento' || p.status === 'cancelado' || p.status === 'pausado' || p.status === 'planejado' || p.status === 'concluido' || p.status === 'desconhecido') {
    return p.status;
  }
  const prog = getProgress(p);
  if (prog === 0) return 'nao-iniciado';
  if (prog === 100) return 'concluido';
  if (prog >= 75) return 'final';
  return 'em-andamento';
}
function getOverallHealth(p) {
  const vals = [p.healthEmotional, p.healthRelational, p.healthSpiritual, p.healthPhysical].filter(Boolean);
  if (vals.length === 0) return 'na';
  if (vals.some(v => v === 'critica')) return 'critica';
  if (vals.some(v => v === 'atencao')) return 'atencao';
  return 'boa';
}
function healthScore(p) {
  const m = { boa: 3, atencao: 2, critica: 1, '': 0 };
  return (m[p.healthEmotional]||0) + (m[p.healthRelational]||0) + (m[p.healthSpiritual]||0) + (m[p.healthPhysical]||0);
}
function getLastProgressUpdate(p) {
  if (p.progressHistory && p.progressHistory.length) return p.progressHistory[p.progressHistory.length - 1].date;
  return p.startDate || null;
}
function getDaysSinceUpdate(p) {
  const date = getLastProgressUpdate(p);
  if (!date) return null;
  const last = new Date(date + 'T00:00:00');
  const today = new Date('2026-05-14');
  return Math.floor((today - last) / (1000 * 60 * 60 * 24));
}
function getStaleStatus(p) {
  const st = getProjectStatus(p);
  // Concluded / canceled / planned projects don't count as 'stale'
  if (st === 'concluido' || st === 'cancelado' || st === 'planejado' || st === 'desconhecido') return null;
  const days = getDaysSinceUpdate(p);
  if (days === null) return null;
  if (days >= 120) return 'critico';
  if (days >= 60) return 'atencao';
  return 'em-dia';
}
function getDeadlineInfo(deadline) {
  if (!deadline) return { cls: '', days: null };
  const d = new Date(deadline);
  const now = new Date('2026-05-14');
  const days = Math.ceil((d - now) / (1000 * 60 * 60 * 24));
  if (days < 0) return { cls: 'overdue', days };
  if (days < 90) return { cls: 'soon', days };
  return { cls: 'ok', days };
}
function getPriority(p) {
  const h = getOverallHealth(p);
  const s = getStaleStatus(p);
  const st = getProjectStatus(p);
  if (st === 'cancelado') return 'canceled';
  if (st === 'pausado') return 'paused';
  if (h === 'critica' || s === 'critico') return 'critical';
  if (h === 'atencao' || s === 'atencao') return 'warning';
  if (st === 'concluido') return 'completed';
  if (st === 'planejado') return 'planned';
  if (st === 'desconhecido') return 'unknown';
  return 'default';
}
function formatDate(ds, locale='pt-BR') {
  if (!ds) return '—';
  return new Date(ds + 'T00:00:00').toLocaleDateString(locale, { day: '2-digit', month: 'short', year: 'numeric' });
}
function escapeHtml(str) {
  if (str === null || str === undefined) return '';
  return String(str).replace(/[&<>"']/g, c => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
}

