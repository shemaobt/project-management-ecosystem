// Aggregate book/story progress arrays into legacy totals
function rollUpProgress(p) {
  const items = [...(p.bookProgress || []), ...(p.storyProgress || []), ...(p.otherProgress || [])];
  if (items.length === 0) return null;
  let tr = 0, co = 0, ap = 0, total = 0;
  items.forEach(it => {
    total += +it.chapters || 0;
    tr += +it.translated || 0;
    co += +it.communityChecked || 0;
    ap += +it.mentorApproved || 0;
  });
  return { translated: tr, community: co, approved: ap, total };
}

